def get_words_for_lessons(lesson_ids: List[int]) -> List[str]:
    """Return flat list of greek words for given lesson DB IDs. Sorted by priority."""
    result = []
    seen = set()
    word_objs = []
    for lid in lesson_ids:
        for w in LESSONS_BY_ID.get(lid, {}).get('words', []):
            if w['greek'] not in seen:
                seen.add(w['greek'])
                word_objs.append(w)
    word_objs.sort(key=lambda x: x.get('general_priority', 10))
    return [w['greek'] for w in word_objs]
